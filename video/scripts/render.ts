// Renders every scene frame by frame in headless Chrome, encodes the segments, lays the voiceover
// under them and writes out/starcoach-demo.mp4.
// Usage: bun scripts/render.ts [--fps 30] [--jobs 4] [--only s03,s08] [--stills]
//   --stills  only writes out/still-<scene>.png at 70% of each scene (fast layout check)
import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { spawn } from "node:child_process";
import puppeteer, { type Browser } from "puppeteer-core";
import { VIDEO_DIR } from "./env";
import { FFMPEG, run } from "./ff";

const args = process.argv.slice(2);
const opt = (name: string, def: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : def;
};
const FPS = Number(opt("fps", "30"));
const JOBS = Number(opt("jobs", "4"));
const ONLY = opt("only", "").split(",").filter(Boolean);
const STILLS = args.includes("--stills");
const LEAD = 0.3; // silence before the narration starts
const TAIL = 0.7; // silence after it ends
const CHROME = process.env.CHROME_PATH ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";

const scenes: Array<{ id: string; text: string }> = JSON.parse(readFileSync(join(VIDEO_DIR, "narration.json"), "utf8"));
const manifest = JSON.parse(readFileSync(join(VIDEO_DIR, "audio", "manifest.json"), "utf8"));
const outDir = join(VIDEO_DIR, "out");
const segDir = join(VIDEO_DIR, "frames");
mkdirSync(outDir, { recursive: true });
mkdirSync(segDir, { recursive: true });

writeFileSync(
  join(VIDEO_DIR, "scenes", "narration.js"),
  `// Generated by scripts/render.ts from narration.json\nwindow.NARRATION = ${JSON.stringify(Object.fromEntries(scenes.map((s) => [s.id, s.text])))};\n`,
);

const plan = scenes.map((s) => {
  const audio = manifest[s.id]?.duration;
  if (!audio) throw new Error(`no audio for ${s.id}; run bun scripts/tts.ts`);
  const frames = Math.round((LEAD + audio + TAIL) * FPS);
  return { id: s.id, audio, frames, d: frames / FPS };
});

const sceneUrl = (p: (typeof plan)[number]) =>
  `file://${join(VIDEO_DIR, "scenes", "index.html")}?scene=${p.id}&lead=${LEAD}&audio=${p.audio}&d=${p.d}`;

async function openScene(browser: Browser, p: (typeof plan)[number]) {
  const page = await browser.newPage();
  await page.setViewport({ width: 1920, height: 1080, deviceScaleFactor: 1 });
  const problems: string[] = [];
  page.on("pageerror", (e) => problems.push(String(e)));
  page.on("requestfailed", (r) => problems.push(`failed to load ${r.url()}`));
  await page.goto(sceneUrl(p), { waitUntil: "load" });
  await page.waitForFunction("window.__ready === true", { timeout: 20000 });
  problems.push(...((await page.evaluate("window.__errors")) as string[]));
  if (problems.length) throw new Error(`${p.id}: ${problems.join("; ")}`);
  return page;
}

async function renderScene(browser: Browser, p: (typeof plan)[number]) {
  const page = await openScene(browser, p);
  const file = join(segDir, `${p.id}.mp4`);
  const ff = spawn(FFMPEG, [
    "-y", "-loglevel", "error",
    "-f", "image2pipe", "-framerate", String(FPS), "-c:v", "mjpeg", "-i", "-",
    "-c:v", "libx264", "-preset", "medium", "-crf", "18", "-pix_fmt", "yuv420p", "-r", String(FPS),
    "-movflags", "+faststart", file,
  ], { stdio: ["pipe", "inherit", "inherit"] });
  const done = new Promise<void>((res, rej) => ff.on("close", (c) => (c === 0 ? res() : rej(new Error(`ffmpeg ${p.id} exit ${c}`)))));
  const t0 = Date.now();
  for (let f = 0; f < p.frames; f++) {
    await page.evaluate((t) => (window as any).seek(t), f / FPS);
    const buf = await page.screenshot({ type: "jpeg", quality: 92, optimizeForSpeed: true });
    if (!ff.stdin.write(buf)) await new Promise((r) => ff.stdin.once("drain", r));
  }
  ff.stdin.end();
  await done;
  await page.close();
  console.log(`${p.id}: ${p.frames} frames (${p.d.toFixed(2)}s) in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}

const browser = await puppeteer.launch({
  executablePath: CHROME,
  headless: true,
  args: ["--allow-file-access-from-files", "--force-color-profile=srgb", "--hide-scrollbars", "--font-render-hinting=none"],
});
try {
  const todo = plan.filter((p) => !ONLY.length || ONLY.includes(p.id));
  if (STILLS) {
    for (const p of todo) {
      const page = await openScene(browser, p);
      await page.evaluate((t) => (window as any).seek(t), p.d * 0.8);
      await page.screenshot({ path: join(outDir, `still-${p.id}.png`) as `${string}.png` });
      await page.close();
      console.log(`still-${p.id}.png`);
    }
    process.exit(0);
  }
  const queue = [...todo];
  await Promise.all(
    Array.from({ length: JOBS }, async () => {
      for (let p = queue.shift(); p; p = queue.shift()) await renderScene(browser, p);
    }),
  );
} finally {
  await browser.close();
}

const missing = plan.filter((p) => !existsSync(join(segDir, `${p.id}.mp4`)));
if (missing.length) throw new Error(`missing segments: ${missing.map((m) => m.id).join(",")}`);

// Audio: each clip delayed by LEAD and padded to exactly its scene length, then joined.
const wavs: string[] = [];
for (const p of plan) {
  const wav = join(segDir, `${p.id}.wav`);
  run(FFMPEG, [
    "-y", "-loglevel", "error", "-i", join(VIDEO_DIR, "audio", `${p.id}.mp3`),
    "-af", `adelay=${Math.round(LEAD * 1000)}:all=1,apad,afade=t=out:st=${(p.d - 0.12).toFixed(3)}:d=0.12`,
    "-t", p.d.toFixed(6), "-ar", "48000", "-ac", "2", "-c:a", "pcm_s16le", wav,
  ]);
  wavs.push(wav);
}
const list = (files: string[]) => files.map((f) => `file '${f}'`).join("\n") + "\n";
writeFileSync(join(segDir, "video.txt"), list(plan.map((p) => join(segDir, `${p.id}.mp4`))));
writeFileSync(join(segDir, "audio.txt"), list(wavs));
const out = join(outDir, "starcoach-demo.mp4");
run(FFMPEG, [
  "-y", "-loglevel", "error",
  "-f", "concat", "-safe", "0", "-i", join(segDir, "video.txt"),
  "-f", "concat", "-safe", "0", "-i", join(segDir, "audio.txt"),
  "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k",
  "-movflags", "+faststart", "-shortest", out,
]);
console.log(`wrote ${out} (${plan.reduce((a, p) => a + p.d, 0).toFixed(1)}s)`);
