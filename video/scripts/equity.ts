// Builds scenes/equity-data.js (scene 8 equity curve) from the 180-day backtest decision log.
// Usage: bun scripts/equity.ts [path/to/backtest.jsonl]
// Keeps the committed file if the log is missing, so the video still builds without logs/.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { VIDEO_DIR } from "./env";

const START = 5_000_000;
const log = process.argv[2] ?? join(VIDEO_DIR, "..", "logs", "backtest-2026-10-23T17-11-18-677Z.jsonl");
const out = join(VIDEO_DIR, "scenes", "equity-data.js");

if (!existsSync(log)) {
  console.log(`equity: ${log} not found, keeping ${existsSync(out) ? "existing data" : "smooth fallback curve"}`);
  process.exit(0);
}

const exits = readFileSync(log, "utf8")
  .trim()
  .split("\n")
  .map((l) => JSON.parse(l))
  .filter((e) => e.event === "exit");

// Simulated time: entry unix seconds are the id suffix; exit = entry + heldHours.
const t = exits.map((e) => Number(String(e.id).split("_").pop()) + Number(e.heldHours ?? 0) * 3600);
const t0 = Math.min(...t.map((x, i) => x - Number(exits[i].heldHours ?? 0) * 3600));
let eq = START;
const points: Array<[number, number]> = [[0, START]];
exits.forEach((e, i) => {
  eq += Number(e.pnlTmn);
  points.push([Math.max(points[points.length - 1][0], +((t[i] - t0) / 86400).toFixed(3)), Math.round(eq)]);
});
writeFileSync(out, `// Generated by scripts/equity.ts from ${log.split("/").pop()}\nwindow.EQUITY = ${JSON.stringify({ start: START, points })};\n`);
console.log(`equity: ${exits.length} exits, end ${(eq / 1e6).toFixed(3)}M, span ${points[points.length - 1][0].toFixed(1)} days`);
